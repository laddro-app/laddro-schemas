#!/usr/bin/env node
// Generate standalone JSON Schema (Draft 2020-12) documents from the OpenAPI 3.1
// component schemas. OpenAPI 3.1 component schemas ARE JSON Schema 2020-12, so we
// can lift `components.schemas` verbatim into `$defs` and rewrite every
// `#/components/schemas/` reference to `#/$defs/`.
//
// Output: ts/dist/json/<name>.schema.json  + a tiny ESM wrapper <name>.js so the
// object can be imported via `@laddro-app/schemas/json/<name>`.
//
// Run from repo root: node scripts/generate-json-schema.mjs

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..");
const OUT_DIR = resolve(repoRoot, "ts/dist/json");

// Dependencies (yaml, ajv) live in ts/node_modules, but this script sits in
// scripts/. Anchor module resolution at the ts package so imports resolve there.
const tsRequire = createRequire(resolve(repoRoot, "ts/package.json"));
function tsImport(specifier) {
  return import(pathToFileURL(tsRequire.resolve(specifier)).href);
}
const { default: YAML } = await tsImport("yaml");

const TARGETS = [
  {
    spec: "resume/resume.v1.yaml",
    root: "Resume",
    out: "resume",
    id: "https://schemas.laddro.com/resume/v1/resume-content.schema.json",
    title: "Laddro Resume Content",
  },
  {
    spec: "cover-letter/cover-letter.v1.yaml",
    root: "CoverLetter",
    out: "cover-letter",
    id: "https://schemas.laddro.com/cover-letter/v1/cover-letter-content.schema.json",
    title: "Laddro Cover Letter Content",
  },
];

const REF_PREFIX = "#/components/schemas/";
const NEW_PREFIX = "#/$defs/";

// Recursively rewrite every `$ref: '#/components/schemas/X'` to `#/$defs/X`.
function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node && typeof node === "object") {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && typeof value === "string" && value.startsWith(REF_PREFIX)) {
        out[key] = NEW_PREFIX + value.slice(REF_PREFIX.length);
      } else {
        out[key] = rewriteRefs(value);
      }
    }
    return out;
  }
  return node;
}

// Normalize OpenAPI 3.0-style `nullable: true` (which is NOT valid JSON Schema
// 2020-12) into the 2020-12 form:
//   { type: "X", nullable: true }   -> { type: ["X", "null"] }
//   { $ref: "...", nullable: true } -> { anyOf: [{ $ref: "..." }, { type: "null" }] }
function normalizeNullable(node) {
  if (Array.isArray(node)) return node.map(normalizeNullable);
  if (!node || typeof node !== "object") return node;

  const mapped = {};
  for (const [k, v] of Object.entries(node)) mapped[k] = normalizeNullable(v);

  if (mapped.nullable === true) {
    delete mapped.nullable;
    if ("$ref" in mapped) {
      const { $ref, ...rest } = mapped;
      return { ...rest, anyOf: [{ $ref }, { type: "null" }] };
    }
    if (typeof mapped.type === "string") {
      mapped.type = [mapped.type, "null"];
    } else if (Array.isArray(mapped.type)) {
      if (!mapped.type.includes("null")) mapped.type = [...mapped.type, "null"];
    } else {
      // No type to widen; fall back to anyOf with null.
      return { anyOf: [mapped, { type: "null" }] };
    }
  } else if (mapped.nullable === false) {
    delete mapped.nullable;
  }

  return mapped;
}

function generate(target) {
  const specPath = resolve(repoRoot, target.spec);
  const doc = YAML.parse(readFileSync(specPath, "utf8"));

  const schemas = doc?.components?.schemas;
  if (!schemas || typeof schemas !== "object") {
    throw new Error(`${target.spec}: no components.schemas found`);
  }
  if (!schemas[target.root]) {
    throw new Error(
      `${target.spec}: root type "${target.root}" not found. ` +
        `Available: ${Object.keys(schemas).join(", ")}`
    );
  }

  const version = doc?.info?.version;
  if (!version) throw new Error(`${target.spec}: missing info.version`);

  const $defs = normalizeNullable(rewriteRefs(schemas));

  const schema = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: target.id,
    title: target.title,
    version,
    $ref: `#/$defs/${target.root}`,
    $defs,
  };

  mkdirSync(OUT_DIR, { recursive: true });

  const jsonPath = resolve(OUT_DIR, `${target.out}.schema.json`);
  writeFileSync(jsonPath, JSON.stringify(schema, null, 2) + "\n", "utf8");

  // Tiny ESM + types wrapper so `import x from '@laddro-app/schemas/json/<name>'`
  // resolves a plain object without relying on host JSON-import support.
  const jsPath = resolve(OUT_DIR, `${target.out}.js`);
  writeFileSync(
    jsPath,
    `// AUTO-GENERATED by scripts/generate-json-schema.mjs — do not edit.\n` +
      `export default ${JSON.stringify(schema)};\n`,
    "utf8"
  );

  const dtsPath = resolve(OUT_DIR, `${target.out}.d.ts`);
  writeFileSync(
    dtsPath,
    `// AUTO-GENERATED by scripts/generate-json-schema.mjs — do not edit.\n` +
      `declare const schema: Record<string, unknown>;\n` +
      `export default schema;\n`,
    "utf8"
  );

  return { jsonPath, schema, defCount: Object.keys($defs).length };
}

// Self-check: the emitted document must itself be a valid JSON Schema 2020-12,
// and every internal $ref must resolve to an existing $def.
async function validate(name, schema) {
  // Structural check: every #/$defs/X ref resolves.
  const refs = new Set();
  (function collect(node) {
    if (Array.isArray(node)) return node.forEach(collect);
    if (node && typeof node === "object") {
      for (const [k, v] of Object.entries(node)) {
        if (k === "$ref" && typeof v === "string" && v.startsWith(NEW_PREFIX)) {
          refs.add(v.slice(NEW_PREFIX.length));
        } else collect(v);
      }
    }
  })(schema);
  for (const ref of refs) {
    if (!(ref in schema.$defs)) {
      throw new Error(`${name}: dangling $ref "#/$defs/${ref}"`);
    }
  }

  // Compile with ajv/2020 if available (dev dependency).
  try {
    const { default: Ajv2020 } = await tsImport("ajv/dist/2020.js");
    const { default: addFormats } = await tsImport("ajv-formats");
    const ajv = new Ajv2020({ strict: false, allErrors: true });
    addFormats(ajv);
    ajv.compile(schema);
    console.log(`  ✓ ${name}: ajv 2020 compiled OK (${refs.size} internal refs resolve)`);
  } catch (err) {
    if (err?.code === "ERR_MODULE_NOT_FOUND" || err?.code === "MODULE_NOT_FOUND") {
      console.log(`  ✓ ${name}: structural check OK (${refs.size} refs resolve); ajv not installed, skipped compile`);
    } else {
      throw new Error(`${name}: ajv compile failed: ${err.message}`);
    }
  }
}

async function main() {
  for (const target of TARGETS) {
    const { jsonPath, schema, defCount } = generate(target);
    console.log(`Generated ${jsonPath} (root: ${target.root}, ${defCount} $defs, $id: ${schema.$id})`);
    await validate(target.out, schema);
  }
  console.log("Done.");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
